//! Explicit public-source pilot for receipt-backed knowledge compilation.
//! Queries stay local. A retry preserves the exact source, compiler and signed
//! job identity; an ambiguous outcome never creates another purchase.
use std::future::Future;
use std::path::PathBuf;
use std::pin::Pin;
use std::time::Duration;

use anyhow::{ensure, Context, Result};
use covenant_compute_protocol::knowledge::{
    knowledge_digest, knowledge_input, knowledge_repository_parts, parse_knowledge_output,
    KnowledgeCompileRequest, KnowledgeCompileResult, MAX_KNOWLEDGE_SOURCE_BYTES,
};
use covenant_compute_protocol::JobKind;
use covenant_identity::LocalIdentity;
use serde_json::{json, Value};

use crate::{BuyerConfig, DispatchOutcome, JobRequest, PurchaseBook, PurchaseEntry};

#[derive(Debug, Clone)]
pub struct RemoteCompileOptions {
    pub repository: String,
    pub compiler_image_sha256: String,
    pub price_micro_usdc: Option<u64>,
    pub max_price_micro_usdc: u64,
    pub deadline_ms: u64,
    pub idempotency_key: Option<String>,
    pub dry_run: bool,
    pub purchase_home: PathBuf,
}

#[derive(Debug)]
pub enum RemoteCompileOutcome {
    Preview(Value),
    Compiled {
        result: KnowledgeCompileResult,
        outcome: DispatchOutcome,
    },
}

type SourceVerifier = for<'a> fn(
    &'a KnowledgeCompileRequest,
) -> Pin<Box<dyn Future<Output = Result<()>> + Send + 'a>>;

fn public_verifier(
    request: &KnowledgeCompileRequest,
) -> Pin<Box<dyn Future<Output = Result<()>> + Send + '_>> {
    Box::pin(verify_public_source(request))
}

pub fn prepare_request(
    source: Value,
    options: &RemoteCompileOptions,
) -> Result<KnowledgeCompileRequest> {
    // Typed normalization rejects hidden fields and credential material before
    // any content is transmitted, even to the public provenance checker.
    let mut source: covenant_knowledge::SourceSet = serde_json::from_value(source)?;
    covenant_knowledge::validate_source(&source)?;
    source.files.sort_by(|a, b| a.path.cmp(&b.path));
    // Capture exclusions can reveal ignored private filenames even when all
    // selected file bytes are public. Only public file content crosses the
    // remote boundary; parser diagnostics are regenerated by the compiler.
    source.diagnostics.clear();
    let source = serde_json::to_value(source)?;
    let commit = source
        .pointer("/git/revision")
        .and_then(Value::as_str)
        .context("remote compile requires a pinned committed source snapshot")?
        .to_owned();
    let request = KnowledgeCompileRequest {
        schema_version: 1,
        repository: options.repository.clone(),
        commit,
        compiler_image_sha256: options.compiler_image_sha256.clone(),
        source_sha256: knowledge_digest(&source)?,
        source,
    };
    request.validate()?;
    Ok(request)
}

/// Anonymous HTTPS checks prove every transmitted source file byte is already
/// present at the public pinned revision. No credentials, Git hooks or repository commands
/// execute; redirects are refused rather than followed to an unexpected host.
pub async fn verify_public_source(request: &KnowledgeCompileRequest) -> Result<()> {
    request.validate()?;
    let (owner, repo) = knowledge_repository_parts(&request.repository)?;
    let public = reqwest::Client::builder()
        .timeout(Duration::from_secs(30))
        .redirect(reqwest::redirect::Policy::none())
        .user_agent("covenant-knowledge-public-source/1")
        .build()?;
    let metadata = public
        .get(format!("https://api.github.com/repos/{owner}/{repo}"))
        .send()
        .await
        .context("verify public GitHub repository")?;
    ensure!(
        metadata.status().is_success(),
        "public repository verification unavailable ({}); nothing was submitted",
        metadata.status()
    );
    let metadata: Value = serde_json::from_slice(&read_public_body(metadata, 64 * 1024).await?)?;
    ensure!(
        metadata.get("private") == Some(&Value::Bool(false)),
        "remote pilot accepts only anonymously accessible public repositories"
    );
    for file in request.source["files"]
        .as_array()
        .context("source files missing")?
    {
        let path = file["path"].as_str().context("source path missing")?;
        let content = file["content"].as_str().context("source content missing")?;
        let mut url = reqwest::Url::parse("https://raw.githubusercontent.com/")?;
        url.path_segments_mut()
            .map_err(|_| anyhow::anyhow!("invalid public source origin"))?
            .extend([owner, repo, &request.commit])
            .extend(path.split('/'));
        let response = public
            .get(url)
            .send()
            .await
            .with_context(|| format!("verify public source {path}"))?;
        ensure!(
            response.status().is_success(),
            "public source {path} at the pinned commit is unavailable ({}); nothing was submitted",
            response.status()
        );
        let bytes = read_public_body(response, MAX_KNOWLEDGE_SOURCE_BYTES).await?;
        ensure!(bytes==content.as_bytes(),"local source differs from public commit at {path}; dirty or unpublished code is not sent");
    }
    Ok(())
}

async fn read_public_body(mut response: reqwest::Response, cap: usize) -> Result<Vec<u8>> {
    let mut bytes = Vec::new();
    while let Some(chunk) = response.chunk().await? {
        ensure!(
            bytes.len().saturating_add(chunk.len()) <= cap,
            "public source response exceeds its byte ceiling"
        );
        bytes.extend_from_slice(&chunk);
    }
    Ok(bytes)
}

pub async fn compile_remote(
    http: &reqwest::Client,
    config: &BuyerConfig,
    identity: &LocalIdentity,
    source: Value,
    options: RemoteCompileOptions,
) -> Result<RemoteCompileOutcome> {
    compile_remote_with(
        http,
        config,
        identity,
        source,
        options,
        public_verifier,
        true,
    )
    .await
}

async fn compile_remote_with(
    http: &reqwest::Client,
    config: &BuyerConfig,
    identity: &LocalIdentity,
    source: Value,
    options: RemoteCompileOptions,
    verify_source: SourceVerifier,
    require_daily_budget: bool,
) -> Result<RemoteCompileOutcome> {
    ensure!(
        (1_000..=600_000).contains(&options.deadline_ms),
        "knowledge deadline must be 1,000..=600,000 milliseconds"
    );
    let request = prepare_request(source, &options)?;
    let input = knowledge_input(&request)?;
    let model = request.model()?;
    if options.dry_run {
        ensure!(
            options.idempotency_key.is_none(),
            "--dry-run cannot combine with --idempotency-key"
        );
        verify_source(&request).await?;
        let price = quote(http, config, &model, &options).await?;
        return Ok(RemoteCompileOutcome::Preview(json!({
            "dry_run":true,"model":model,"repository":request.repository,"commit":request.commit,
            "source_sha256":request.source_sha256,"source_bytes":serde_json::to_vec(&request.source)?.len(),
            "price_micro_usdc":price,"deadline_ms":options.deadline_ms,"submitted":false
        })));
    }
    let key = options
        .idempotency_key
        .as_deref()
        .context("remote compilation requires --idempotency-key to preserve uncertain purchases")?;
    ensure!(
        (1..=128).contains(&key.len()),
        "idempotency key must contain 1..=128 bytes"
    );
    ensure!(
        options.purchase_home.is_absolute(),
        "purchase home must be absolute"
    );
    std::fs::create_dir_all(&options.purchase_home)?;
    // Endpoint namespace prevents a job signed for one coordinator being
    // silently replayed against another deployment under the same CLI key.
    let endpoint = crate::durable_budget::canonical_endpoint(&config.coordinator_url)?;
    let namespace = crate::sha256_hex(endpoint.as_bytes());
    let lock_path = options
        .purchase_home
        .join(format!("knowledge-purchases-{namespace}.lock"));
    let lock = tokio::task::spawn_blocking(move || -> Result<std::fs::File> {
        let mut open = std::fs::OpenOptions::new();
        open.create(true).read(true).write(true).truncate(false);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            open.mode(0o600).custom_flags(libc::O_NOFOLLOW);
        }
        let file = open.open(lock_path)?;
        file.lock()?;
        Ok(file)
    })
    .await??;
    let book = PurchaseBook::open(
        &options
            .purchase_home
            .join(format!("knowledge-purchases-{namespace}.jsonl")),
    )?;
    let scoped = format!("{}:{key}", identity.agent_id().pubkey_base58());
    let existing = book.lookup(&scoped);
    let settled = existing.as_ref().is_some_and(PurchaseEntry::settled);
    let envelope = if let Some(entry) = existing {
        if let Some(conflict) = entry.conflicting_argument(
            JobKind::BatchJob,
            &input,
            Some(&model),
            None,
            None,
            None,
            options.price_micro_usdc,
            Some(options.deadline_ms),
        ) {
            anyhow::bail!("idempotency key already names a different {conflict}; repeat the original request to recover it");
        }
        entry.envelope
    } else {
        verify_source(&request).await?;
        let price = quote(http, config, &model, &options).await?;
        if require_daily_budget {
            ensure!(crate::durable_budget::DurableBudget::from_env(
                &identity.agent_id().pubkey_base58(),&config.coordinator_url)?.is_some(),
                "remote compile requires COVENANT_COMPUTE_DAILY_BUDGET_MICRO_USDC and its existing durable budget journal");
        }
        let envelope = crate::sign_envelope(
            config,
            identity,
            JobRequest {
                kind: JobKind::BatchJob,
                input,
                model: Some(model),
                gpu_class: None,
                min_vram_gb: None,
                min_reputation_bps: None,
                price_micro_usdc: price,
                deadline_ms: options.deadline_ms,
            },
        )?;
        book.record(PurchaseEntry {
            key: scoped.clone(),
            envelope: envelope.clone(),
            opened_at_ms: crate::epoch_ms(),
            receipt_id: None,
            voided: false,
        })?;
        envelope
    };
    if !settled && require_daily_budget {
        ensure!(
            crate::durable_budget::DurableBudget::from_env(
                &identity.agent_id().pubkey_base58(),
                &config.coordinator_url
            )?
            .is_some(),
            "an unfinished remote compile must retain its configured durable daily budget before retrying"
        );
    }
    let outcome = if settled {
        // A completed retry is signed reads only: no second POST or provider call.
        crate::poll_receipt_and_verify(http, config, identity, envelope).await?
    } else {
        // The existing dispatcher reserves the shared daily allowance before
        // submission and keeps uncertain outcomes reserved. All retries retain
        // the original envelope, including terminal rejected/failed requests.
        crate::dispatch_signed(http, config, identity, envelope).await?
    };
    book.settle(&scoped, outcome.receipt.receipt.job_id)?;
    let result = parse_knowledge_output(&outcome.output, &request)?;
    let snapshot: covenant_knowledge::Snapshot = serde_json::from_value(result.snapshot.clone())?;
    covenant_knowledge::validate_snapshot(&snapshot)?;
    drop(lock);
    Ok(RemoteCompileOutcome::Compiled { result, outcome })
}

async fn quote(
    http: &reqwest::Client,
    config: &BuyerConfig,
    model: &str,
    options: &RemoteCompileOptions,
) -> Result<u64> {
    let floor = crate::cheapest_matching_ask(
        http,
        config,
        JobKind::BatchJob,
        Some(model),
        None,
        None,
        None,
    )
    .await?
    .context("no operator serves this exact pinned knowledge compiler; nothing was submitted")?;
    let price = options.price_micro_usdc.unwrap_or(floor);
    ensure!(
        price >= floor,
        "offered price is below the pinned compiler's current ask"
    );
    ensure!(
        price <= options.max_price_micro_usdc,
        "knowledge price exceeds the existing per-call ceiling"
    );
    Ok(price)
}

